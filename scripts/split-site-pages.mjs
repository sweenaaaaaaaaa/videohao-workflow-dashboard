import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(projectRoot, 'src/data/site-pages.generated.ts');
const source = await readFile(sourcePath, 'utf8');
const declaration = 'export const sitePages: Record<string, SitePageData> = ';
const objectStart = source.indexOf(declaration) + declaration.length;
const objectEnd = source.lastIndexOf('\n};');

if (objectStart < declaration.length || objectEnd < objectStart) {
  throw new Error('Unable to locate the generated sitePages object');
}

const pages = JSON.parse(source.slice(objectStart, objectEnd + 2));
const localeGroups = { zh: {}, en: {}, ru: {}, es: {} };
const index = {};
const sharedTemplatePaths = ['/pro_category/dexiafuwuche/'];

for (const [pathname, page] of Object.entries(pages)) {
  const locale = pathname.match(/^\/(en|ru|es)(?:\/|$)/)?.[1] || 'zh';
  localeGroups[locale][pathname] = page;
  index[pathname] = { ...page, bodyHtml: '' };
}

for (const locale of ['en', 'ru', 'es']) {
  for (const templatePath of sharedTemplatePaths) {
    localeGroups[locale][templatePath] = pages[templatePath];
  }
}

for (const [locale, localePages] of Object.entries(localeGroups)) {
  const output = `// Generated by scripts/split-site-pages.mjs.\nimport type { SitePageData } from './site-page-types';\n\nexport const sitePages = ${JSON.stringify(localePages, null, 2)} satisfies Record<string, SitePageData>;\n`;
  await writeFile(path.join(projectRoot, `src/data/site-pages.${locale}.generated.ts`), output);
}

const indexOutput = `// Generated by scripts/split-site-pages.mjs.\nimport type { SitePageData } from './site-page-types';\n\nexport const sitePageIndex = ${JSON.stringify(index, null, 2)} satisfies Record<string, SitePageData>;\n`;
await writeFile(path.join(projectRoot, 'src/data/site-page-index.generated.ts'), indexOutput);

console.log(
  JSON.stringify({
    pages: Object.keys(pages).length,
    locales: Object.fromEntries(Object.entries(localeGroups).map(([locale, localePages]) => [locale, Object.keys(localePages).length])),
  }),
);
